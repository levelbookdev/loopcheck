/// <reference path="../pb_data/types.d.ts" />
//
// Migration O — Instrument Calibration Records (ADR 0016).
//
// Calibration is a purpose-built append-only ledger. A loop check proves the
// signal path; these records prove the instrument read true, preserving the
// paired as-found/as-left readings and the certificate state of the standard
// used. `next_due` and the tag badge are derived by readers, never stored.

migrate((app) => {
  const AUTH = '@request.auth.id != ""';
  const tags = app.findCollectionByNameOrId("tags");

  const standards = new Collection({
    type: "base",
    name: "test_standards",
    // Field capture reads this registry without an account. Registry changes
    // are office actions and use the auth boundary already established by
    // ADR 0011. Certificates attach through `attachments`.
    listRule: "",
    viewRule: "",
    createRule: AUTH,
    updateRule: AUTH,
    deleteRule: null,
    fields: [
      { name: "name", type: "text", required: true, presentable: true },
      { name: "model", type: "text" },
      { name: "serial", type: "text", required: true },
      { name: "owner", type: "text" },
      { name: "cert_date", type: "date", required: true },
      { name: "cert_due_date", type: "date", required: true },
      { name: "created", type: "autodate", onCreate: true, onUpdate: false },
      { name: "updated", type: "autodate", onCreate: true, onUpdate: true },
    ],
    indexes: [
      "CREATE INDEX `idx_test_standards_due` ON `test_standards` (`cert_due_date`)",
      "CREATE INDEX `idx_test_standards_serial` ON `test_standards` (`serial`)",
    ],
  });
  app.save(standards);

  const calibrations = new Collection({
    type: "base",
    name: "calibrations",
    listRule: "",
    viewRule: "",
    // Creation goes through /api/calibrations/capture so the header, every
    // point, the optional report, and the server-derived expiry flag land in
    // one transaction. Direct writes could strand an incomplete immutable
    // record, so they are closed even to admins through the records API.
    createRule: null,
    updateRule: null,
    deleteRule: null,
    fields: [
      { name: "tag", type: "relation", required: true, maxSelect: 1,
        collectionId: tags.id, cascadeDelete: false },
      { name: "standard", type: "relation", required: true, maxSelect: 1,
        collectionId: standards.id, cascadeDelete: false },
      { name: "technician", type: "text", required: true },
      { name: "company", type: "text" },
      { name: "performed_at", type: "date", required: true },
      { name: "interval_months", type: "number", required: true,
        onlyInt: true, min: 1, max: 120 },
      { name: "result", type: "select", required: true, maxSelect: 1,
        values: ["pass", "fail", "adjusted_pass"] },
      { name: "notes", type: "text" },
      { name: "standard_expired_at_use", type: "bool" },

      // Frozen registry copies: later correction or recertification of the
      // editable standard must not rewrite what this calibration relied on.
      { name: "standard_name", type: "text", required: true },
      { name: "standard_model", type: "text" },
      { name: "standard_serial", type: "text", required: true },
      { name: "standard_cert_due_date", type: "date", required: true },

      // Idempotency key generated by the phone outbox. A retry after the
      // response is lost returns this record instead of duplicating evidence.
      { name: "client_token", type: "text", required: true, hidden: true },
      { name: "created", type: "autodate", onCreate: true, onUpdate: false },
    ],
    indexes: [
      "CREATE INDEX `idx_calibrations_tag_date` ON `calibrations` (`tag`, `performed_at`)",
      "CREATE UNIQUE INDEX `idx_calibrations_client_token` ON `calibrations` (`client_token`)",
    ],
  });
  app.save(calibrations);

  const points = new Collection({
    type: "base",
    name: "calibration_points",
    listRule: "",
    viewRule: "",
    createRule: null,
    updateRule: null,
    deleteRule: null,
    fields: [
      { name: "calibration", type: "relation", required: true, maxSelect: 1,
        collectionId: calibrations.id, cascadeDelete: false },
      { name: "sequence", type: "number", required: true, onlyInt: true, min: 1 },
      { name: "test_point", type: "text", required: true },
      { name: "expected_value", type: "number" },
      { name: "as_found", type: "number" },
      { name: "as_left", type: "number" },
      { name: "unit", type: "text", required: true },
      { name: "within_tolerance", type: "bool" },
      { name: "created", type: "autodate", onCreate: true, onUpdate: false },
    ],
    indexes: [
      "CREATE UNIQUE INDEX `idx_calibration_points_sequence` ON `calibration_points` (`calibration`, `sequence`)",
    ],
  });
  app.save(points);
}, (app) => {
  app.delete(app.findCollectionByNameOrId("calibration_points"));
  app.delete(app.findCollectionByNameOrId("calibrations"));
  app.delete(app.findCollectionByNameOrId("test_standards"));
});
